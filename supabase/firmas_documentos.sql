on conflict (id) do update set public = false, file_size_limit = 2097152, allowed_mime_types = array['image/png'];

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('firmas-documentos', 'firmas-documentos', false, 2097152, array['image/png'])
on conflict (id) do update set public = false, file_size_limit = 2097152, allowed_mime_types = array['image/png'];

drop policy if exists "usuarios gestionan su imagen de firma" on storage.objects;
create policy "usuarios gestionan su imagen de firma"
  on storage.objects for all to authenticated
  using (
    bucket_id = 'firmas-usuarios'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  )
  with check (
    bucket_id = 'firmas-usuarios'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  );

drop policy if exists "firmantes guardan su firma del archivo" on storage.objects;
create policy "firmantes guardan su firma del archivo"
  on storage.objects for insert to authenticated
  with check (
    bucket_id = 'firmas-documentos'
    and exists (
      select 1 from public.firma_documento as signature_request
      where signature_request.id::text = (storage.foldername(name))[1]
        and signature_request.firmante_auth_user_id = (select auth.uid())
        and signature_request.estado = 'pendiente'
        and (storage.foldername(name))[2] = (select auth.uid())::text
    )
  );

drop policy if exists "usuarios autorizados consultan firmas de archivos" on storage.objects;
create policy "usuarios autorizados consultan firmas de archivos"
  on storage.objects for select to authenticated
  using (
    (bucket_id = 'firmas-usuarios' and (storage.foldername(name))[1] = (select auth.uid())::text)
    or (
      bucket_id = 'firmas-documentos'
      and exists (
        select 1
        from public.firma_documento as signature_request
        join public.archivo as file on file.id = signature_request.archivo_id
        where signature_request.id::text = (storage.foldername(name))[1]
          and (
            signature_request.firmante_auth_user_id = (select auth.uid())
            or (select auth.jwt() ->> 'email') = 'admin@gmail.com'
            or exists (
              select 1 from public.usuario as admin_account
              where admin_account.auth_user_id = (select auth.uid()) and admin_account.rol = 'admin'
            )
            or exists (
              select 1 from public.usuario as account
              where account.auth_user_id = (select auth.uid())
                and account.rol = 'intermedio'
                and account.id_empresa = file.empresa_id
            )
          )
      )
    )
  );

create or replace function public.registrar_firma_documento(
  p_firma_documento_id bigint,
  p_firma_path text,
  p_sha256_documento text
)
returns public.firma_documento
language plpgsql
security definer
set search_path = public, storage, pg_temp
as $$
declare
  signature_request public.firma_documento;
begin
  if auth.uid() is null then
    raise exception 'Debes iniciar sesión para firmar.';
  end if;

  select * into signature_request
  from public.firma_documento
  where id = p_firma_documento_id
    and firmante_auth_user_id = auth.uid()
    and estado = 'pendiente'
  for update;

  if not found then
    raise exception 'La solicitud no existe, ya fue firmada o no te pertenece.';
  end if;

  if p_firma_path <> format('%s/%s.png', p_firma_documento_id, auth.uid()) then
    raise exception 'La ruta de la firma no es válida.';
  end if;

  if p_sha256_documento !~ '^[0-9a-f]{64}$' then
    raise exception 'La huella del documento no es válida.';
  end if;

  if not exists (
    select 1 from storage.objects
    where bucket_id = 'firmas-documentos' and name = p_firma_path
  ) then
    raise exception 'No se encontró la copia de tu firma.';
  end if;

  update public.firma_documento
  set estado = 'firmado', firmada_en = now(), firma_path = p_firma_path,
      sha256_documento = p_sha256_documento
  where id = p_firma_documento_id
  returning * into signature_request;

  return signature_request;
end;
$$;

revoke all on function public.registrar_firma_documento(bigint, text, text) from public, anon;
grant execute on function public.registrar_firma_documento(bigint, text, text) to authenticated;

create or replace function public.proteger_archivo_con_firmas()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if exists (select 1 from public.firma_documento where archivo_id = old.id) then
    raise exception 'Este archivo ya tiene un proceso de firma y no se puede reemplazar ni borrar.';
  end if;
  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

drop trigger if exists proteger_archivo_con_firmas on public.archivo;
create trigger proteger_archivo_con_firmas
  before update of nombre, storage_path, mime_type, datos or delete on public.archivo
  for each row execute function public.proteger_archivo_con_firmas();

-- Los firmantes básicos pueden abrir solo los archivos que les asignaron.
-- La comprobación pasa por una función SECURITY DEFINER para leer firma_documento
-- sin reevaluar su RLS y así evitar la recursión infinita (42P17) entre las
-- políticas de archivo y firma_documento ("database schema is invalid or incompatible").
create or replace function public.firma_asignada_a_archivo(p_archivo_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1
    from public.firma_documento as signature_request
    where signature_request.archivo_id = p_archivo_id
      and signature_request.firmante_auth_user_id = auth.uid()
  )
$$;

revoke all on function public.firma_asignada_a_archivo(bigint) from public, anon;
grant execute on function public.firma_asignada_a_archivo(bigint) to authenticated;

drop policy if exists "assigned signers can read requested files" on public.archivo;
create policy "assigned signers can read requested files"
  on public.archivo for select to authenticated
  using (public.firma_asignada_a_archivo(id));

drop policy if exists "assigned signers can read requested document objects" on storage.objects;
create policy "assigned signers can read requested document objects"
  on storage.objects for select to authenticated
  using (
    bucket_id = 'documentos-empresa'
    and exists (
      select 1
      from public.archivo as file
      join public.firma_documento as signature_request on signature_request.archivo_id = file.id
      where file.storage_path = storage.objects.name
        and signature_request.firmante_auth_user_id = (select auth.uid())
    )
  );
