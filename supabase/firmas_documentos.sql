-- Firma electrónica interna para archivos de empresa.
-- Ejecutar una vez desde el SQL Editor de Supabase.

alter table public.archivo
  add column if not exists requiere_firma boolean not null default false;

create table if not exists public.firma_usuario (
  auth_user_id uuid primary key references auth.users (id) on delete cascade,
  storage_path text not null unique,
  mime_type text not null default 'image/png',
  actualizada_en timestamptz not null default now()
);

create table if not exists public.firma_documento (
  id bigint generated by default as identity primary key,
  archivo_id bigint not null references public.archivo (id) on delete restrict,
  firmante_auth_user_id uuid not null references auth.users (id) on delete restrict,
  firmante_nombre text not null,
  firmante_correo text,
  estado text not null default 'pendiente' check (estado in ('pendiente', 'firmado')),
  solicitada_en timestamptz not null default now(),
  firmada_en timestamptz,
  firma_path text,
  sha256_documento text,
  creado_por uuid references auth.users (id) on delete set null,
  constraint firma_documento_archivo_firmante_unique unique (archivo_id, firmante_auth_user_id),
  constraint firma_documento_firma_coherente check (
    (estado = 'pendiente' and firmada_en is null and firma_path is null and sha256_documento is null)
    or (estado = 'firmado' and firmada_en is not null and firma_path is not null and sha256_documento is not null)
  )
);

create index if not exists firma_documento_firmante_estado_idx
  on public.firma_documento (firmante_auth_user_id, estado, solicitada_en desc);
create index if not exists firma_documento_archivo_idx
  on public.firma_documento (archivo_id);

alter table public.firma_usuario enable row level security;
alter table public.firma_documento enable row level security;

grant select, insert, update, delete on public.firma_usuario to authenticated;
grant select, insert on public.firma_documento to authenticated;
grant usage, select on sequence public.firma_documento_id_seq to authenticated;
revoke all on public.firma_usuario, public.firma_documento from anon;

drop policy if exists "cada usuario administra su firma" on public.firma_usuario;
create policy "cada usuario administra su firma"
  on public.firma_usuario for all to authenticated
  using (auth_user_id = (select auth.uid()))
  with check (auth_user_id = (select auth.uid()));

drop policy if exists "usuarios ven sus solicitudes de firma" on public.firma_documento;
create policy "usuarios ven sus solicitudes de firma"
  on public.firma_documento for select to authenticated
  using (
    firmante_auth_user_id = (select auth.uid())
    or (select auth.jwt() ->> 'email') = 'admin@gmail.com'
    or exists (
      select 1 from public.usuario as admin_account
      where admin_account.auth_user_id = (select auth.uid()) and admin_account.rol = 'admin'
    )
    or exists (
      select 1
      from public.archivo as file
      join public.usuario as account on account.id_empresa = file.empresa_id
      where file.id = public.firma_documento.archivo_id
        and account.auth_user_id = (select auth.uid())
        and account.rol = 'intermedio'
    )
  );

drop policy if exists "admin solicita firmas" on public.firma_documento;
create policy "admin solicita firmas"
  on public.firma_documento for insert to authenticated
  with check (
    creado_por = (select auth.uid())
    and exists (
      select 1
      where (select auth.jwt() ->> 'email') = 'admin@gmail.com'
        or exists (
          select 1 from public.usuario as admin_account
          where admin_account.auth_user_id = (select auth.uid()) and admin_account.rol = 'admin'
        )
    )
    and (
      firmante_auth_user_id = (select auth.uid())
      or exists (
        select 1
        from public.archivo as file
        join public.usuario as signer_account on signer_account.id_empresa = file.empresa_id
        where file.id = archivo_id
          and signer_account.auth_user_id = firmante_auth_user_id
      )
    )
  );

