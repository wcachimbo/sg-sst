-- Registro de auditorías recibidas por empresa y seguimiento de sus hallazgos.
-- Ejecuta este archivo una vez desde el SQL Editor de Supabase.

create table if not exists public.auditoria_empresa (
  id bigint generated by default as identity primary key,
  fecha_creacion timestamptz not null default now(),
  empresa_id bigint not null references public.empresa (id) on delete cascade,
  fecha_auditoria timestamptz not null,
  tipo text not null check (tipo in ('Interna', 'Externa', 'Certificación', 'Cliente', 'Entidad de control')),
  entidad_auditora text,
  auditor_nombre text not null,
  auditor_correo text,
  objetivo text not null,
  alcance text not null,
  areas_auditadas text[] not null default '{}',
  descripcion text,
  responsable_empresa text not null,
  estado text not null default 'Programada'
    check (estado in ('Programada', 'En curso', 'Cerrada', 'Cancelada')),
  token_hallazgos_hash text,
  token_hallazgos_expira timestamptz,
  correo_hallazgos_enviado timestamptz,
  creado_por uuid references auth.users (id) on delete set null,
  constraint auditoria_empresa_areas_no_vacias check (cardinality(areas_auditadas) > 0)
);

create table if not exists public.persona_auditoria (
  id bigint generated by default as identity primary key,
  auditoria_id bigint not null references public.auditoria_empresa (id) on delete cascade,
  trabajador_cedula varchar not null references public.empleado (cedula) on delete cascade,
  constraint persona_auditoria_unica unique (auditoria_id, trabajador_cedula)
);

create table if not exists public.hallazgo_auditoria (
  id bigint generated by default as identity primary key,
  fecha_creacion timestamptz not null default now(),
  auditoria_id bigint not null references public.auditoria_empresa (id) on delete cascade,
  tipo text not null check (tipo in ('No conformidad', 'Observación', 'Oportunidad de mejora', 'Conformidad')),
  descripcion text not null,
  accion_correctiva text,
  responsable text,
  fecha_compromiso date,
  estado text not null default 'Abierto' check (estado in ('Abierto', 'En proceso', 'Cerrado')),
  registrado_por_auditor boolean not null default false
);

-- Estas columnas también actualizan instalaciones donde ya se ejecutó una versión previa del SQL.
alter table public.auditoria_empresa add column if not exists auditor_correo text;
alter table public.auditoria_empresa add column if not exists token_hallazgos_hash text;
alter table public.auditoria_empresa add column if not exists token_hallazgos_expira timestamptz;
alter table public.auditoria_empresa add column if not exists correo_hallazgos_enviado timestamptz;
alter table public.hallazgo_auditoria add column if not exists registrado_por_auditor boolean not null default false;

create table if not exists public.evidencia_auditoria (
  id bigint generated by default as identity primary key,
  fecha timestamptz not null default now(),
  auditoria_id bigint not null references public.auditoria_empresa (id) on delete cascade,
  nombre_archivo text not null,
  ruta_storage text not null unique,
  tipo_mime text not null,
  tamano_bytes bigint not null default 0 check (tamano_bytes between 0 and 10485760),
  origen text not null default 'Auditor externo' check (origen in ('Auditor externo', 'Empresa'))
);

create index if not exists auditoria_empresa_fecha_idx
  on public.auditoria_empresa (empresa_id, fecha_auditoria desc);
create index if not exists persona_auditoria_auditoria_idx
  on public.persona_auditoria (auditoria_id);
create index if not exists hallazgo_auditoria_fecha_idx
  on public.hallazgo_auditoria (auditoria_id, fecha_creacion desc);
create index if not exists evidencia_auditoria_auditoria_fecha_idx
  on public.evidencia_auditoria (auditoria_id, fecha desc);
create unique index if not exists auditoria_empresa_token_hash_idx
  on public.auditoria_empresa (token_hallazgos_hash) where token_hallazgos_hash is not null;

alter table public.auditoria_empresa enable row level security;
alter table public.persona_auditoria enable row level security;
alter table public.hallazgo_auditoria enable row level security;
alter table public.evidencia_auditoria enable row level security;

