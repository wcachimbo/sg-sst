-- Agenda de visitas presenciales por empresa y sus participantes.
-- Ejecuta este archivo una vez desde SQL Editor de Supabase.

create table if not exists public.visita_empresa (
  id bigint generated by default as identity primary key,
  fecha_creacion timestamptz not null default now(),
  empresa_id bigint not null references public.empresa (id) on delete cascade,
  fecha_visita timestamptz not null,
  descripcion text not null,
  areas_revision text[] not null default '{}',
  encargado text not null,
  estado text not null default 'Programada'
    check (estado in ('Programada', 'Realizada', 'Cancelada')),
  creado_por uuid references auth.users (id) on delete set null,
  constraint visita_empresa_areas_no_vacias check (cardinality(areas_revision) > 0)
);

create table if not exists public.persona_visita (
  id bigint generated by default as identity primary key,
  visita_id bigint not null references public.visita_empresa (id) on delete cascade,
  trabajador_cedula varchar not null references public.empleado (cedula) on delete cascade,
  constraint persona_visita_unica unique (visita_id, trabajador_cedula)
);

create index if not exists visita_empresa_fecha_idx
  on public.visita_empresa (empresa_id, fecha_visita);
create index if not exists persona_visita_visita_idx
  on public.persona_visita (visita_id);

alter table public.visita_empresa enable row level security;
alter table public.persona_visita enable row level security;

grant usage on schema public to authenticated;
grant select, insert, update, delete on public.visita_empresa to authenticated;
grant select, insert, delete on public.persona_visita to authenticated;
grant select on public.empleado to authenticated;

do $$
declare
  sequence_name regclass;
begin
  sequence_name := pg_get_serial_sequence('public.visita_empresa', 'id');
  if sequence_name is not null then execute format('grant usage, select on sequence %s to authenticated', sequence_name); end if;
  sequence_name := pg_get_serial_sequence('public.persona_visita', 'id');
  if sequence_name is not null then execute format('grant usage, select on sequence %s to authenticated', sequence_name); end if;
end $$;

-- Los usuarios de empresa pueden consultar sus trabajadores para seleccionar participantes.
drop policy if exists "cuentas pueden consultar empleados para visitas" on public.empleado;
create policy "cuentas pueden consultar empleados para visitas"
  on public.empleado for select to authenticated
  using (
    (select auth.jwt() ->> 'email') = 'admin@gmail.com'
    or exists (
      select 1 from public.usuario as cuenta
      where cuenta.auth_user_id = (select auth.uid())
        and cuenta.rol = 'intermedio'
        and cuenta.id_empresa = public.empleado.id_empresa
    )
  );

drop policy if exists "cuentas consultan visitas de su empresa" on public.visita_empresa;
create policy "cuentas consultan visitas de su empresa"
  on public.visita_empresa for select to authenticated
  using (
    (select auth.jwt() ->> 'email') = 'admin@gmail.com'
    or exists (
      select 1 from public.usuario as cuenta
      where cuenta.auth_user_id = (select auth.uid())
        and cuenta.rol = 'intermedio'
        and cuenta.id_empresa = public.visita_empresa.empresa_id
    )
  );

drop policy if exists "cuentas programan visitas de su empresa" on public.visita_empresa;
create policy "cuentas programan visitas de su empresa"
  on public.visita_empresa for insert to authenticated
  with check (
    (select auth.jwt() ->> 'email') = 'admin@gmail.com'
    or (
      creado_por = (select auth.uid())
      and exists (
        select 1 from public.usuario as cuenta
        where cuenta.auth_user_id = (select auth.uid())
          and cuenta.rol = 'intermedio'
          and cuenta.id_empresa = public.visita_empresa.empresa_id
      )
    )
  );

drop policy if exists "cuentas actualizan visitas de su empresa" on public.visita_empresa;
create policy "cuentas actualizan visitas de su empresa"
  on public.visita_empresa for update to authenticated
  using (
    (select auth.jwt() ->> 'email') = 'admin@gmail.com'
    or exists (
      select 1 from public.usuario as cuenta
      where cuenta.auth_user_id = (select auth.uid())
        and cuenta.rol = 'intermedio'
        and cuenta.id_empresa = public.visita_empresa.empresa_id
    )
  )
  with check (
    (select auth.jwt() ->> 'email') = 'admin@gmail.com'
    or exists (
      select 1 from public.usuario as cuenta
      where cuenta.auth_user_id = (select auth.uid())
        and cuenta.rol = 'intermedio'
        and cuenta.id_empresa = public.visita_empresa.empresa_id
    )
  );

drop policy if exists "administrador elimina visitas" on public.visita_empresa;
create policy "administrador elimina visitas"
  on public.visita_empresa for delete to authenticated
  using ((select auth.jwt() ->> 'email') = 'admin@gmail.com');

drop policy if exists "cuentas consultan participantes de visitas" on public.persona_visita;
create policy "cuentas consultan participantes de visitas"
  on public.persona_visita for select to authenticated
  using (exists (
    select 1 from public.visita_empresa as visita
    where visita.id = public.persona_visita.visita_id
  ));

drop policy if exists "cuentas agregan participantes de visitas" on public.persona_visita;
create policy "cuentas agregan participantes de visitas"
  on public.persona_visita for insert to authenticated
  with check (exists (
    select 1 from public.visita_empresa as visita
    where visita.id = public.persona_visita.visita_id
  ));

drop policy if exists "administrador elimina participantes de visitas" on public.persona_visita;
create policy "administrador elimina participantes de visitas"
  on public.persona_visita for delete to authenticated
  using ((select auth.jwt() ->> 'email') = 'admin@gmail.com');
