-- Valida la respuesta en el servidor y deja reintentar hasta acertar.
create or replace function public.responder_pregunta_capacitacion(p_pregunta_id bigint, p_opcion_id bigint)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_usuario uuid := auth.uid();
  v_correcta boolean;
  v_capacitacion_id bigint;
  v_tipo_asignacion text;
  v_cedula varchar;
  v_empresa_id bigint;
  v_video_id bigint;
begin
  if v_usuario is null then raise exception 'Debes iniciar sesión.'; end if;
  select c.id, c.empresa_id, c.tipo_asignacion, q.video_id
    into v_capacitacion_id, v_empresa_id, v_tipo_asignacion, v_video_id
  from public.pregunta_capacitacion p
  join public.cuestionario_capacitacion q on q.id = p.cuestionario_id
  join public.capacitacion c on c.id = q.capacitacion_id
  where p.id = p_pregunta_id and c.estado = 'Publicada';
  if v_capacitacion_id is null then raise exception 'La pregunta no está disponible.'; end if;
  select u.cedula into v_cedula from public.usuario u where u.auth_user_id = v_usuario and u.id_empresa = v_empresa_id;
  if v_cedula is null then raise exception 'Tu cuenta no está asociada a esta empresa.'; end if;
  if v_tipo_asignacion = 'personas' and not exists (
    select 1 from public.asignacion_capacitacion a where a.capacitacion_id = v_capacitacion_id and a.trabajador_cedula = v_cedula
  ) then raise exception 'Esta capacitación no está asignada a tu usuario.'; end if;
  if v_video_id is not null and not exists (
    select 1 from public.video_capacitacion v where v.id = v_video_id and v.activo
  ) then raise exception 'El video de esta pregunta está oculto.'; end if;
  if not exists (select 1 from public.opcion_pregunta_capacitacion o where o.id = p_opcion_id and o.pregunta_id = p_pregunta_id) then
    raise exception 'La opción seleccionada no pertenece a esta pregunta.';
  end if;
  select k.opcion_id = p_opcion_id into v_correcta from public.clave_pregunta_capacitacion k where k.pregunta_id = p_pregunta_id;
  if v_correcta is null then raise exception 'Esta pregunta aún no tiene respuesta correcta configurada.'; end if;
  insert into public.progreso_pregunta_capacitacion (usuario_id, pregunta_id, opcion_actual_id, intentos, correcta, actualizada_en)
  values (v_usuario, p_pregunta_id, p_opcion_id, 1, v_correcta, now())
  on conflict (usuario_id, pregunta_id) do update set
    opcion_actual_id = excluded.opcion_actual_id,
    intentos = public.progreso_pregunta_capacitacion.intentos + 1,
    correcta = public.progreso_pregunta_capacitacion.correcta or excluded.correcta,
    actualizada_en = now();
  return v_correcta;
end;
$$;
revoke all on function public.responder_pregunta_capacitacion(bigint, bigint) from public;
grant execute on function public.responder_pregunta_capacitacion(bigint, bigint) to authenticated;
