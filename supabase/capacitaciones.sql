-- Lectura del catálogo: administradores ven todo; cada cuenta ve solo cursos
-- publicados para su empresa y, si aplica, asignados a su cédula.
drop policy if exists "cuentas consultan capacitaciones asignadas" on public.capacitacion;
create policy "cuentas consultan capacitaciones asignadas"
  on public.capacitacion for select to authenticated
  using (
    (select auth.jwt() ->> 'email') = 'admin@gmail.com'
    or (
      estado = 'Publicada'
      and exists (
        select 1 from public.usuario as cuenta
        where cuenta.auth_user_id = (select auth.uid())
          and cuenta.id_empresa = public.capacitacion.empresa_id
          and (
            public.capacitacion.tipo_asignacion = 'toda_empresa'
            or exists (
              select 1 from public.asignacion_capacitacion as asignacion
              where asignacion.capacitacion_id = public.capacitacion.id
                and asignacion.trabajador_cedula = cuenta.cedula
            )
          )
      )
    )
  );

drop policy if exists "administrador administra capacitaciones" on public.capacitacion;
