-- Cursos con videos externos ordenados, asignación por empresa/persona y avance por usuario.
-- Ejecuta este archivo desde el SQL Editor de Supabase.

create table if not exists public.capacitacion (
  id bigint generated by default as identity primary key,
  fecha_creacion timestamptz not null default now(),
  nombre text not null,
  descripcion text not null default '',
  empresa_id bigint not null references public.empresa (id) on delete cascade,
  tipo_asignacion text not null default 'toda_empresa'
    check (tipo_asignacion in ('toda_empresa', 'personas')),
  estado text not null default 'Publicada'
    check (estado in ('Borrador', 'Publicada', 'Archivada')),
  creado_por uuid references auth.users (id) on delete set null
);

-- CREATE TABLE IF NOT EXISTS no actualiza una tabla capacitacion preexistente.
-- Asegura las columnas que necesita esta versión antes de crear las políticas.
alter table public.capacitacion
  add column if not exists fecha_creacion timestamptz not null default now(),
  add column if not exists nombre text not null default '',
  add column if not exists descripcion text not null default '',
  add column if not exists empresa_id bigint,
  add column if not exists tipo_asignacion text not null default 'toda_empresa',
  add column if not exists estado text not null default 'Publicada',
  add column if not exists creado_por uuid;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'capacitacion_empresa_id_fkey'
      and conrelid = 'public.capacitacion'::regclass
  ) then
    alter table public.capacitacion
      add constraint capacitacion_empresa_id_fkey
      foreign key (empresa_id) references public.empresa (id) on delete cascade;
  end if;
  if not exists (
    select 1 from pg_constraint
    where conname = 'capacitacion_creado_por_fkey'
      and conrelid = 'public.capacitacion'::regclass
  ) then
    alter table public.capacitacion
      add constraint capacitacion_creado_por_fkey
      foreign key (creado_por) references auth.users (id) on delete set null;
  end if;
end $$;

create table if not exists public.video_capacitacion (
  id bigint generated by default as identity primary key,
  fecha_creacion timestamptz not null default now(),
  capacitacion_id bigint not null references public.capacitacion (id) on delete cascade,
  titulo text not null,
  descripcion text,
  enlace text not null,
  orden integer not null check (orden > 0),
  obligatorio boolean not null default true,
  activo boolean not null default true,
  constraint video_capacitacion_orden_unico unique (capacitacion_id, orden)
);

alter table public.video_capacitacion
  add column if not exists activo boolean not null default true;

create table if not exists public.asignacion_capacitacion (
  id bigint generated by default as identity primary key,
  fecha_asignacion timestamptz not null default now(),
  capacitacion_id bigint not null references public.capacitacion (id) on delete cascade,
  trabajador_cedula varchar not null references public.empleado (cedula) on delete cascade,
  constraint asignacion_capacitacion_persona_unica unique (capacitacion_id, trabajador_cedula)
);

create table if not exists public.progreso_video_capacitacion (
  id bigint generated by default as identity primary key,
  usuario_id uuid not null references auth.users (id) on delete cascade,
  video_id bigint not null references public.video_capacitacion (id) on delete cascade,
  completado_en timestamptz not null default now(),
  constraint progreso_video_usuario_unico unique (video_id, usuario_id)
);

-- Cuestionarios ligados a un video (video_id) o al cierre del curso (NULL).
create table if not exists public.cuestionario_capacitacion (
  id bigint generated by default as identity primary key,
  capacitacion_id bigint not null references public.capacitacion (id) on delete cascade,
  video_id bigint references public.video_capacitacion (id) on delete cascade,
  titulo text not null default 'Cuestionario',
  orden integer not null default 1
);

create table if not exists public.pregunta_capacitacion (
  id bigint generated by default as identity primary key,
  cuestionario_id bigint not null references public.cuestionario_capacitacion (id) on delete cascade,
  enunciado text not null,
  tipo text not null check (tipo in ('opcion_multiple', 'verdadero_falso')),
  orden integer not null default 1
);

create table if not exists public.opcion_pregunta_capacitacion (
  id bigint generated by default as identity primary key,
  pregunta_id bigint not null references public.pregunta_capacitacion (id) on delete cascade,
  texto text not null,
  orden integer not null default 1,
  constraint opcion_pregunta_id_pregunta_unico unique (id, pregunta_id)
);

-- La clave correcta queda en una tabla que el alumno no puede consultar.
create table if not exists public.clave_pregunta_capacitacion (
  pregunta_id bigint primary key references public.pregunta_capacitacion (id) on delete cascade,
  opcion_id bigint not null,
  constraint clave_opcion_pregunta_fk foreign key (opcion_id, pregunta_id)
    references public.opcion_pregunta_capacitacion (id, pregunta_id) on delete cascade
);

create table if not exists public.progreso_pregunta_capacitacion (
  usuario_id uuid not null references auth.users (id) on delete cascade,
  pregunta_id bigint not null references public.pregunta_capacitacion (id) on delete cascade,
  opcion_actual_id bigint references public.opcion_pregunta_capacitacion (id) on delete set null,
  intentos integer not null default 0,
  correcta boolean not null default false,
  actualizada_en timestamptz not null default now(),
  primary key (usuario_id, pregunta_id)
);

create index if not exists capacitacion_empresa_estado_idx on public.capacitacion (empresa_id, estado);
create index if not exists video_capacitacion_orden_idx on public.video_capacitacion (capacitacion_id, orden);
create index if not exists asignacion_capacitacion_persona_idx on public.asignacion_capacitacion (trabajador_cedula);
create index if not exists progreso_video_usuario_idx on public.progreso_video_capacitacion (usuario_id);

