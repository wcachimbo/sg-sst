-- Ejecuta este script en el SQL Editor de Supabase para habilitar
-- el registro de accidentes, evidencias y seguimiento por empresa.

create table if not exists public.reporte_accidente (
  id bigint generated by default as identity primary key,
  creado_en timestamp with time zone not null default now(),
  actualizado_en timestamp with time zone not null default now(),
  fecha_reporte timestamp with time zone not null default now(),
  empresa_id bigint not null references public.empresa (id) on delete cascade,
  fecha_ocurrencia timestamp with time zone not null,
  lugar text not null,
  descripcion text not null,
  trabajador_cedula varchar,
  trabajador_nombre text not null,
  estado text not null default 'Reportado'
    check (estado in ('Reportado', 'En seguimiento', 'Cerrado')),
  responsable_seguimiento text,
  reportado_por uuid references auth.users (id) on delete set null,
  constraint reporte_accidente_trabajador_fkey
    foreign key (trabajador_cedula) references public.empleado (cedula) on delete set null
);

create table if not exists public.seguimiento_accidente (
  id bigint generated by default as identity primary key,
  fecha timestamp with time zone not null default now(),
  reporte_accidente_id bigint not null references public.reporte_accidente (id) on delete cascade,
  comentario text not null,
  estado text not null check (estado in ('En seguimiento', 'Cerrado')),
  responsable text,
  creado_por uuid references auth.users (id) on delete set null
);

create table if not exists public.evidencia_accidente (
  id bigint generated by default as identity primary key,
  fecha timestamp with time zone not null default now(),
  reporte_accidente_id bigint not null references public.reporte_accidente (id) on delete cascade,
  nombre_archivo text not null,
  ruta_storage text not null unique,
  tipo_mime text not null,
  tamano_bytes bigint not null default 0 check (tamano_bytes >= 0),
  subido_por uuid references auth.users (id) on delete set null
);

create index if not exists reporte_accidente_empresa_fecha_idx
  on public.reporte_accidente (empresa_id, fecha_ocurrencia desc);
create index if not exists seguimiento_accidente_reporte_fecha_idx
  on public.seguimiento_accidente (reporte_accidente_id, fecha desc);
create index if not exists evidencia_accidente_reporte_fecha_idx
  on public.evidencia_accidente (reporte_accidente_id, fecha);

-- Permite mostrar en el formulario los empleados de la empresa del usuario.
drop policy if exists "cuentas pueden consultar empleados de su empresa" on public.empleado;
create policy "cuentas pueden consultar empleados de su empresa"
  on public.empleado for select to authenticated
  using (
    (select auth.jwt() ->> 'email') = 'admin@gmail.com'
    or exists (
      select 1 from public.usuario as cuenta
      where cuenta.auth_user_id = (select auth.uid())
        and cuenta.rol = 'intermedio'
        and cuenta.id_empresa = public.empleado.id_empresa
    )
  );

alter table public.reporte_accidente enable row level security;
alter table public.seguimiento_accidente enable row level security;
alter table public.evidencia_accidente enable row level security;

grant usage on schema public to authenticated;
grant select, insert, update, delete on public.reporte_accidente to authenticated;
grant select, insert, update, delete on public.seguimiento_accidente to authenticated;
grant select, insert, update, delete on public.evidencia_accidente to authenticated;
grant select on public.empleado to authenticated;

