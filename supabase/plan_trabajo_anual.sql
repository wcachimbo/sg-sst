-- Ejecuta este archivo en el SQL Editor de Supabase para habilitar
-- planes anuales y sus actividades por empresa.

create table if not exists public.plan_trabajo_anual (
  id bigint generated by default as identity primary key,
  fecha timestamp with time zone not null default now(),
  empresa_id bigint not null references public.empresa (id) on delete cascade,
  anio integer not null check (anio between 2000 and 2100),
  nombre text not null default 'Plan anual de trabajo',
  creado_por uuid references auth.users (id) on delete set null,
  constraint plan_trabajo_anual_empresa_anio_unique unique (empresa_id, anio)
);

create table if not exists public.actividad_plan_trabajo_anual (
  id bigint generated by default as identity primary key,
  fecha timestamp with time zone not null default now(),
  plan_id bigint not null references public.plan_trabajo_anual (id) on delete cascade,
  actividad text not null,
  responsable text,
  mes smallint not null check (mes between 1 and 12),
  prioridad text not null default 'Media'
    check (prioridad in ('Alta', 'Media', 'Baja')),
  estado text not null default 'Pendiente'
    check (estado in ('Pendiente', 'En proceso', 'Completado')),
  evidencia text,
  observaciones text,
  orden integer not null default 0
);

create index if not exists plan_trabajo_anual_empresa_anio_idx
  on public.plan_trabajo_anual (empresa_id, anio desc);

create index if not exists actividad_plan_trabajo_anual_plan_orden_idx
  on public.actividad_plan_trabajo_anual (plan_id, orden, id);

alter table public.plan_trabajo_anual enable row level security;
alter table public.actividad_plan_trabajo_anual enable row level security;

grant usage on schema public to authenticated;
grant select, insert, update, delete on public.plan_trabajo_anual to authenticated;
grant select, insert, update, delete on public.actividad_plan_trabajo_anual to authenticated;

do $$
declare
  sequence_name regclass;
begin
  sequence_name := pg_get_serial_sequence('public.plan_trabajo_anual', 'id');
  if sequence_name is not null then
    execute format('grant usage, select on sequence %s to authenticated', sequence_name);
  end if;

  sequence_name := pg_get_serial_sequence('public.actividad_plan_trabajo_anual', 'id');
  if sequence_name is not null then
    execute format('grant usage, select on sequence %s to authenticated', sequence_name);
  end if;
end $$;

drop policy if exists "cuentas pueden consultar planes de su empresa" on public.plan_trabajo_anual;
create policy "cuentas pueden consultar planes de su empresa"
  on public.plan_trabajo_anual for select to authenticated
  using (
    (select auth.jwt() ->> 'email') = 'admin@gmail.com'
    or exists (
      select 1
      from public.usuario as cuenta
      where cuenta.auth_user_id = (select auth.uid())
        and cuenta.id_empresa = public.plan_trabajo_anual.empresa_id
    )
  );

drop policy if exists "administrador gestiona planes anuales" on public.plan_trabajo_anual;
create policy "administrador gestiona planes anuales"
  on public.plan_trabajo_anual for all to authenticated
  using ((select auth.jwt() ->> 'email') = 'admin@gmail.com')
  with check ((select auth.jwt() ->> 'email') = 'admin@gmail.com');

drop policy if exists "cuentas pueden consultar actividades de su empresa" on public.actividad_plan_trabajo_anual;
create policy "cuentas pueden consultar actividades de su empresa"
  on public.actividad_plan_trabajo_anual for select to authenticated
  using (
    (select auth.jwt() ->> 'email') = 'admin@gmail.com'
    or exists (
      select 1
      from public.plan_trabajo_anual as plan
      join public.usuario as cuenta on cuenta.id_empresa = plan.empresa_id
      where plan.id = public.actividad_plan_trabajo_anual.plan_id
        and cuenta.auth_user_id = (select auth.uid())
    )
  );

drop policy if exists "administrador gestiona actividades del plan" on public.actividad_plan_trabajo_anual;
create policy "administrador gestiona actividades del plan"
  on public.actividad_plan_trabajo_anual for all to authenticated
  using ((select auth.jwt() ->> 'email') = 'admin@gmail.com')
  with check (
    (select auth.jwt() ->> 'email') = 'admin@gmail.com'
    and exists (
      select 1 from public.plan_trabajo_anual as plan
      where plan.id = public.actividad_plan_trabajo_anual.plan_id
    )
  );
